CREATE TABLE IF NOT EXISTS TREINAMENTO_COII.MUNICIPIOS (
		ID_MUNI_PREV INT COMMENT 'Identificador do código do município da Previdência Social',
		NU_MUNI_IBGE INT COMMENT 'CODIGO DO MUNICIPIO SEGUNDO O IBGE',
		NU_MUNI_SERPRO SMALLINT COMMENT 'CODIGO DO MUNICIPIO SEGUNDO O SERPRO',
		NM_MUNI STRING COMMENT 'NOME DO MUNICIPIO',
		NU_CEP INT COMMENT 'CODIGO DE ENDERECAMENTO POSTAL DO MUNICIPIO',
		ID_MUNI_ECT INT COMMENT 'IDENTIFICADOR DE CÓDIGO DE MUNICÍPIO SEGUNDO ECT',
		IN_NOME_MUN_IGUAL TINYINT COMMENT 'INDICADOR DE MUNICIPIO COM NOME IGUAL EM OUTRA(S) UF(S)',
		SG_UF STRING,
		IN_MAP TINYINT COMMENT 'INDICADOR DE MUNICIPIO MAPEADO COM CODIGO LOCAL DE CEP',
		ID_REGIAO_METROPOLITANA TINYINT,
		NU_DDD TINYINT COMMENT 'Código DDD (Discagem Direta à Distância) correspondente ao município.',
		QT_POPULACAO INT COMMENT 'População total residente no município, independente de sexo e idade.',
		DT_INIC_VALI DATE COMMENT 'DATA DE INICIO DE VALIDADE',
		ID_MESORREGIAO SMALLINT COMMENT 'Identificador primário da mesoregião',
		ID_UF_PREV TINYINT,
		NU_LATITUDE DECIMAL(8 , 6) COMMENT 'Coordenada de latitude média do município',
		NU_LONGITUDE DECIMAL(9 , 6) COMMENT 'Coordenada de longitude média do município'
	) 
	COMMENT 'Municípios brasileiros'
STORED AS ORC;
